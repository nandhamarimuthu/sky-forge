"""Agent 3 — Functional Automation Agent.

Infers user journeys from HTTP routes (FastAPI, Flask, Express), generates functional test scenarios covering
success paths, failure paths, method/permission checks and unknown routes, and executes the Python scenarios
against an in-process test client inside the network-isolated sandbox. Never targets deployed environments.
"""

