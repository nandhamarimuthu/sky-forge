"""Agent 3 — Functional Automation Agent.

Infers user journeys from HTTP routes in *any* supported stack (FastAPI, Flask, Django, Express/Fastify, NestJS,
Spring, ASP.NET Core, Rails, Laravel, Gin/Echo/chi, actix/axum), generates functional scenarios covering success
paths, failure paths, method/permission checks, content negotiation and unknown routes, and executes the Python
scenarios against an in-process test client inside the network-isolated sandbox. When the repository's Terraform
declares AWS resources, the generated suite is wired to moto fixtures so journeys that touch AWS run offline.
Never targets deployed environments.
"""

