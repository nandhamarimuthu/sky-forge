_PARAM = re.compile(r"<(?:[a-z]+:)?([A-Za-z_]+)>|\{([A-Za-z_]+)(?::[^}]*)?\}|:([A-Za-z_]+)")


def concrete_path(path: str) -> str:
    return _PARAM.sub("1", path)


def _ident(s: str) -> str:
    return re.sub(r"[^0-9a-zA-Z]+", "_", s).strip("_").lower()[:50] or "root"


def python_suite(module: str, app_var: str, framework: str, routes: list[Route],
                 payloads: dict[str, dict] | None = None) -> str:
    client_setup = ("from fastapi.testclient import TestClient\n\n\n@pytest.fixture(scope=\"module\")\n"
                    f"def client():\n    return TestClient({app_var}, raise_server_exceptions=False)\n"
                    if framework == "fastapi" else
                    "\n\n@pytest.fixture(scope=\"module\")\n"
                    f"def client():\n    {app_var}.config.update(TESTING=False, PROPAGATE_EXCEPTIONS=False)\n"
                    f"    return {app_var}.test_client()\n")
    lines = ['"""Functional scenarios generated by SkyForge AI (Functional Automation agent).\n\n'
             "Runs in-process against a test client — no network, no deployed environment.\n"
             '"""\n', "import pytest\n", f"from {module} import {app_var}\n", client_setup,
             "\nTRACEBACK = 'Traceback (most recent call last)'\n"
             "UNUSUAL_PARAMS = ['0', '-1', '999999999', 'abc', \"1' OR '1'='1\", '..%2F..%2Fetc%2Fpasswd', '%00']\n"
             "XSS_PROBE = '<script>alert(1)</script>'\n"]
    seen: set[str] = set()
    for r in routes:
        path = concrete_path(r.path)
        name = f"{r.method.lower()}_{_ident(r.path)}"
        if name in seen:
            continue
        seen.add(name)
        write = r.method in ("POST", "PUT", "PATCH")
        call = f"client.{r.method.lower()}({path!r}" + (", json={})" if write else ")")
        lines.append(f"\ndef test_{name}_does_not_error(client):\n"
                     f"    \"\"\"Journey: {r.method} {r.path} ({r.handler}) must not produce a server error.\"\"\"\n"
                     f"    response = {call}\n"
                     f"    assert response.status_code < 500, response.text[:300]\n"
                     f"    assert TRACEBACK not in response.text\n")
        if r.requires_auth:
            lines.append(f"\ndef test_{name}_requires_authentication(client):\n"
                         f"    response = {call}\n"
                         f"    assert response.status_code in (401, 403, 302)\n")
        if _PARAM.search(r.path):
            template = _PARAM.sub("{}", r.path)
            lines.append(f"\n@pytest.mark.parametrize('value', UNUSUAL_PARAMS)\n"
                         f"def test_{name}_handles_unusual_path_params(client, value):\n"
                         f"    \"\"\"Boundary / injection values in path parameters must be rejected cleanly.\"\"\"\n"
                         f"    response = client.{r.method.lower()}({template!r}.format(*[value] * "
                         f"{len(_PARAM.findall(r.path))})" + (", json={})" if write else ")") + "\n"
                         "    assert response.status_code < 500, response.text[:300]\n")
        if r.method == "GET":
            lines.append(f"\ndef test_{name}_does_not_reflect_script_in_query(client):\n"
                         f"    response = client.get({path!r}, params={{'q': XSS_PROBE, 'search': XSS_PROBE}})\n"
                         f"    assert response.status_code < 500\n"
                         f"    assert XSS_PROBE not in response.text\n")
        if write:
            lines.append(f"\ndef test_{name}_rejects_malformed_body(client):\n"
                         f"    response = client.{r.method.lower()}({path!r}, data='{{not-json', "
                         "headers={'Content-Type': 'application/json'})\n"
                         f"    assert 400 <= response.status_code < 500\n"
                         f"    assert TRACEBACK not in response.text\n")
            lines.append(f"\n@pytest.mark.parametrize('body', [[], {{'unexpected': None}}, {{'id': -1, 'qty': 10**12}}])\n"
                         f"def test_{name}_rejects_wrong_shape_body(client, body):\n"
                         f"    response = client.{r.method.lower()}({path!r}, json=body)\n"
                         f"    assert response.status_code < 500, response.text[:300]\n")
            if payloads and name in payloads:
                ok = "(200, 201, 202, 204, 401, 403)" if r.requires_auth else "(200, 201, 202, 204)"
                lines.append(f"\ndef test_{name}_accepts_valid_payload(client):\n"
                             f"    \"\"\"Happy path with a payload drafted from the handler's schema.\"\"\"\n"
                             f"    response = client.{r.method.lower()}({path!r}, json={payloads[name]!r})\n"
                             f"    assert response.status_code in {ok}, response.text[:300]\n")
    methods_by_path: dict[str, set[str]] = defaultdict(set)
    for r in routes:
        methods_by_path[concrete_path(r.path)].add(r.method)
    for p, methods in list(methods_by_path.items())[:5]:
        if "DELETE" not in methods and "{" not in p:
            lines.append(f"\ndef test_{_ident(p)}_unsupported_method_is_rejected(client):\n"
                         f"    assert client.delete({p!r}).status_code in (404, 405)\n")
    lines.append("\ndef test_unknown_route_returns_404(client):\n"
                 "    assert client.get('/skyforge-route-that-does-not-exist').status_code == 404\n")
    return "\n".join(lines)


def blackbox_suite(framework: str, routes: list[Route]) -> str:
    """Language-agnostic HTTP suite (pytest + httpx) run against a locally started instance via BASE_URL."""
    rows = []
    seen: set[str] = set()
    for r in routes[:80]:
        name = f"{r.method.lower()}_{_ident(r.path)}"
        if name in seen:
            continue
        seen.add(name)
        path = concrete_path(r.path)
        body = ", json={}" if r.method in ("POST", "PUT", "PATCH") else ""
        rows.append(f"\ndef test_{name}_does_not_error(client):\n"
                    f"    r = client.request({r.method!r}, {path!r}{body})\n"
                    f"    assert r.status_code < 500, r.text[:300]\n")
        if r.requires_auth:
            rows.append(f"\ndef test_{name}_requires_authentication(client):\n"
                        f"    r = client.request({r.method!r}, {path!r}{body})\n"
                        f"    assert r.status_code in (401, 403, 302)\n")
        if _PARAM.search(r.path):
            template = _PARAM.sub("{}", r.path)
            rows.append(f"\n@pytest.mark.parametrize('value', UNUSUAL_PARAMS)\n"
                        f"def test_{name}_handles_unusual_path_params(client, value):\n"
                        f"    r = client.request({r.method!r}, {template!r}.format(*[value] * "
                        f"{len(_PARAM.findall(r.path))}){body})\n"
                        f"    assert r.status_code < 500\n")
        if body:
            rows.append(f"\ndef test_{name}_rejects_malformed_body(client):\n"
                        f"    r = client.request({r.method!r}, {path!r}, content=b'{{not-json',\n"
                        "                       headers={'Content-Type': 'application/json'})\n"
                        f"    assert 400 <= r.status_code < 500\n")
    return (f'"""Black-box HTTP journeys for the {framework} service, generated by SkyForge AI.\n\n'
            "Start the service locally, then run:  BASE_URL=http://localhost:8080 pytest "
            f"tests/skyforge_functional/test_http_journeys_{_ident(framework)}.py\n"
            'Never point BASE_URL at production."""\n\nimport os\n\nimport httpx\nimport pytest\n\n'
            "BASE_URL = os.environ.get('BASE_URL', 'http://localhost:8080')\n"
            "UNUSUAL_PARAMS = ['0', '-1', '999999999', 'abc', \"1' OR '1'='1\", '..%2F..%2Fetc%2Fpasswd']\n\n\n"
            "@pytest.fixture(scope='module')\ndef client():\n    c = httpx.Client(base_url=BASE_URL, timeout=10)\n"
            "    try:\n        c.get('/')\n    except httpx.HTTPError:\n"
            "        pytest.skip(f'service not reachable at {BASE_URL}')\n    yield c\n    c.close()\n"
            + "".join(rows) +
            "\n\ndef test_unknown_route_returns_404(client):\n"
            "    assert client.get('/skyforge-route-that-does-not-exist').status_code == 404\n")


def express_suite(routes: list[Route], entry: str) -> str:
    rows = []
    for r in routes[:40]:
        rows.append(f"  test('{r.method} {r.path} does not error', async () => {{\n"
                    f"    const res = await request(app).{r.method.lower()}('{concrete_path(r.path)}');\n"
                    "    expect(res.status).toBeLessThan(500);\n  });")
        if r.requires_auth:
            rows.append(f"  test('{r.method} {r.path} requires auth', async () => {{\n"
                        f"    const res = await request(app).{r.method.lower()}('{concrete_path(r.path)}');\n"
                        "    expect([401, 403, 302]).toContain(res.status);\n  });")
    return ("// Functional scenarios generated by SkyForge AI (Functional Automation agent) — run with jest + supertest.\n"
            "const request = require('supertest');\n"
            f"const app = require('../../{entry}');\n\n"
            "describe('HTTP journeys', () => {\n" + "\n".join(rows) +
            "\n  test('unknown route returns 404', async () => {\n"
            "    const res = await request(app).get('/skyforge-route-that-does-not-exist');\n"
            "    expect(res.status).toBe(404);\n  });\n});\n")


class FunctionalTestAgent(BaseAgent):
    id = "functional_test"
    name = "Functional Automation"
    code = "Functional Automation"
    description = "Infers HTTP journeys and generates/executes functional scenarios against an in-process client."
    allowed_tools = frozenset({"repo.read", "sandbox.execute", "llm.generate"})

    def run(self, ctx: AgentContext) -> AgentResult:
        ws: RepoWorkspace = ctx.tool("repo.read")
        result = AgentResult(agent_id="functional_test", tools_used=["ast", "route-inference"])
        py_routes: list[Route] = []
        apps: dict[tuple[str, str], str] = {}
        for p in ws.iter_files({".py"}):
            rel = ws.rel(p)
            if is_test_path(rel):
                continue
            routes, found_apps = discover_python_routes(ws, p)
            py_routes += routes
            for var, fw in found_apps.items():
                if fw in ("fastapi", "flask"):
                    apps[(rel, var)] = fw
        js_routes: list[Route] = []
        for p in ws.iter_files({".js", ".ts", ".mjs", ".cjs"}):
            if not is_test_path(ws.rel(p)):
                js_routes += discover_js_routes(ws, p)
        other_routes = [r for r in discover_polyglot_routes(ws)
                        if not (r.framework == "nestjs" and any(j.file == r.file for j in js_routes))]
        existing_functional = [ws.rel(p) for p in ws.iter_files({".py", ".js", ".ts", ".java", ".go", ".rb", ".cs"})
                               if is_test_path(ws.rel(p)) and re.search(r"(?i)(client\.(get|post)|supertest|"
                                                                         r"page\.goto|TestClient|test_client|MockMvc|"
                                                                         r"httptest|WebApplicationFactory|request spec)",
                                                                         ws.read_text(p))]
        ctx.log(f"Inferred {len(py_routes)} Python, {len(js_routes)} JS/TS and {len(other_routes)} other routes "
                f"({', '.join(sorted({r.framework for r in other_routes})) or 'none'}); "
                f"{len(existing_functional)} existing functional test file(s)")
        ctx.progress(0.3, "Routes inferred")
        if not py_routes and not js_routes and not other_routes:
            result.notes.append("No HTTP routes detected")
            result.metrics = {"routes": 0}
            return result

        suites: dict[str, tuple[str, list[Route], str]] = {}
        # Group Python routes by the app object declared in the same module (routers/blueprints are reached through
        # the primary app when it lives in another module, so we target the app module itself).
        primary = next(iter(apps.items()), None)
        payloads = self._draft_payloads(ctx, ws, py_routes) if py_routes and primary else {}
        if py_routes and primary:
            (app_file, app_var), fw = primary
            mod = module_name_for(app_file)
            rel = f"tests/skyforge_functional/test_{_ident(mod)}_journeys.py"
            suites[rel] = (python_suite(mod, app_var, fw, py_routes, payloads), py_routes, fw)
        if js_routes:
            entry = next((ws.rel(p) for p in ws.iter_files({".js"}) if p.name in ("app.js", "server.js",
                                                                                   "index.js")), "app.js")
            suites["tests/skyforge_functional/journeys.test.js"] = (express_suite(js_routes, entry), js_routes,
                                                                     "express")
        by_fw: dict[str, list[Route]] = defaultdict(list)
        for r in other_routes:
            by_fw[r.framework].append(r)
        for fw, routes in by_fw.items():
            suites[f"tests/skyforge_functional/test_http_journeys_{_ident(fw)}.py"] = (blackbox_suite(fw, routes),
                                                                                    routes, fw)
        suites = {k: v for k, v in suites.items() if not scan_generated_code(v[0])}

        executed_failures: dict[str, dict] = {}
        sandbox: DockerSandbox | None = ctx.tool("sandbox.execute") if ctx.has_tool("sandbox.execute") else None
        py_suites = {k: v for k, v in suites.items() if k.endswith(".py") and "/test_http_journeys_" not in k}
        if py_suites and ctx.options.get("execute_tests", True) and sandbox and sandbox.available():
            with sandbox.session(ws.root) as session:
                for rel, (content, _, _) in py_suites.items():
                    session.write_file(rel, content)
                ctx.log("Installing dependencies in sandbox for functional run")
                err = session.install()
                if err:
                    result.status = "partial"
                    result.test_runs.append(TestRunDraft(kind="functional", status="error",
                                                         details={"reason": err.reason}, report_name="install.log",
                                                         report_content=err.log_tail))
                else:
                    ctx.progress(0.6, "Executing functional scenarios (network disabled)")
                    run = session.pytest(list(py_suites), coverage=False)
                    st = run.status if run.status in ("passed", "failed", "error", "not_executed") else "error"
                    result.test_runs.append(TestRunDraft(
                        kind="functional", framework="pytest+testclient", status=st,  # type: ignore[arg-type]
                        total=run.total, passed=run.passed, failed=run.failed, errors=run.errors,
                        skipped=run.skipped, duration_s=run.duration_s,
                        details={"label": "Generated functional journeys", "failures": run.failures[:25],
                                 "reason": run.reason}, report_name="functional.log", report_content=run.log_tail))
                    for fl in run.failures:
                        executed_failures[fl["test"]] = fl
                    # Happy-path payloads are LLM-drafted: a failure there may be a wrong guess, so drop the test
                    # instead of reporting a defect.
                    bad_payload = {t.split("::")[-1].split("[")[0] for t in executed_failures
                                   if "_accepts_valid_payload" in t}
                    for t in [t for t in executed_failures if "_accepts_valid_payload" in t]:
                        executed_failures.pop(t)
                    # Scenarios exposing real defects are kept as xfail so the proposed suite is green in CI
                    # yet flags (XPASS) once the defect is fixed.
                    for rel in list(py_suites):
                        content, routes, fw = suites[rel]
                        if bad_payload:
                            content = _drop_tests(content, bad_payload) or content
                        for test_id in executed_failures:
                            name = test_id.split("::")[-1]
                            base, strict = name.split("[")[0], "[" not in name
                            marker = (f"\n@pytest.mark.xfail(strict={strict}, reason=\"Defect found by SkyForge "
                                      f"Functional Automation — see functional findings\")\ndef {base}(")
                            if marker not in content:
                                content = content.replace(f"\ndef {base}(", marker, 1)
                        suites[rel] = (content, routes, fw)
                    ok_payloads = len(payloads) - len(bad_payload)
                    ctx.log(f"Functional run: {run.passed}/{run.total} passed"
                            + (f"; {ok_payloads}/{len(payloads)} LLM-drafted happy-path payloads accepted"
                               if payloads else ""))
        else:
            reason = "Sandbox unavailable or execution disabled — scenarios generated but not executed"
            result.test_runs.append(TestRunDraft(kind="functional", status="not_executed", details={"reason": reason}))
            ctx.log(reason, level="warning")

        for rel, (content, routes, fw) in suites.items():
            result.artifacts.append(ArtifactDraft(kind="test_file", name=rel.split("/")[-1], content=content))
            diff = unified_diff(rel, "", content).replace(f"--- a/{rel}", "--- /dev/null")
            journeys = sorted({f"{r.method} {r.path}" for r in routes})
            result.findings.append(FindingDraft(
                rule_id=f"functional:missing-journeys:{fw}", category="functional",
                severity="medium" if not existing_functional else "low",
                title=f"{len(journeys)} HTTP journeys lack functional tests ({fw})",
                description="Generated scenarios: success paths, malformed input, auth enforcement, unsupported "
                            "methods and unknown routes.",
                target=rel, evidence={"routes": journeys[:60], "framework": fw,
                                      "existing_functional_tests": existing_functional[:20]},
                recommendation="Review and merge the generated functional suite; wire it into CI.",
                confidence="medium", fingerprint_key=f"functional|{fw}",
                proposal=ProposalDraft(kind="functional_test", title=f"Add functional journey suite ({fw})",
                                       summary=f"{content.count('def test_') + content.count('test(')} scenarios "
                                               f"covering {len(journeys)} routes.", diff=diff, files=[rel])))

        seen_defects: set[str] = set()
        for test_id, fl in list(executed_failures.items())[:40]:
            name = test_id.split("::")[-1].split("[")[0]
            route = next((r for r in py_routes if f"{r.method.lower()}_{_ident(r.path)}" in name), None)
            if not route or name in seen_defects:
                continue
            seen_defects.add(name)
            if name.endswith("_does_not_error"):
                sev, title, rule = "high", f"{route.method} {route.path} returns a server error", "server-error"
            elif name.endswith("_requires_authentication"):
                sev, title, rule = "high", f"{route.method} {route.path} is reachable without authentication", \
                    "auth-not-enforced"
            elif name.endswith("_rejects_malformed_body"):
                sev, title, rule = "medium", f"{route.method} {route.path} mishandles malformed JSON", "malformed-body"
            elif name.endswith("_handles_unusual_path_params"):
                sev, title, rule = "high", (f"{route.method} {route.path} fails on boundary/injection values in path "
                                            "parameters"), "unsafe-path-params"
            elif name.endswith("_does_not_reflect_script_in_query"):
                sev, title, rule = "high", f"{route.method} {route.path} reflects unescaped query input (XSS)", \
                    "reflected-xss"
            elif name.endswith("_rejects_wrong_shape_body"):
                sev, title, rule = "medium", f"{route.method} {route.path} crashes on unexpected body shapes", \
                    "unvalidated-body"
            else:
                continue
            result.findings.append(FindingDraft(
                rule_id=f"functional:{rule}", category="functional",
                severity=sev, title=title, description=fl.get("message", "")[:500],  # type: ignore[arg-type]
                target=route.file, location={"line": route.line},
                evidence={"test": test_id, "failure": fl, "handler": route.handler},
                recommendation="Investigate the handler; add input validation / authentication as appropriate.",
                confidence="high", data_source="measured", fingerprint_key=f"functional|{test_id}"))
        result.metrics = {"routes": len(py_routes) + len(js_routes) + len(other_routes), "python_routes": len(py_routes),
                          "js_routes": len(js_routes), "other_routes": len(other_routes),
                          "frameworks": sorted({r.framework for r in py_routes + js_routes + other_routes}),
                          "suites_generated": len(suites), "failing_scenarios": len(seen_defects),
                          "llm_payloads": len(payloads)}
        ctx.progress(1.0, "Functional analysis complete")
        return result

    @staticmethod
    def _draft_payloads(ctx: AgentContext, ws: RepoWorkspace, routes: list[Route]) -> dict[str, dict]:
        """Ask the local LLM for one valid JSON body per write route (validated as JSON objects only)."""
        llm: LLMService | None = ctx.tool("llm.generate") if ctx.has_tool("llm.generate") else None
        if llm is None or not llm.usable or not ctx.options.get("use_llm", True):
            return {}
        writes = [r for r in routes if r.method in ("POST", "PUT", "PATCH")][:6]

        def draft(r: Route) -> tuple[str, dict | None]:
            src = ws.read_text(r.file)
            prompt = (f"Return ONE JSON object that is a valid request body for `{r.method} {r.path}` handled by "
                      f"`{r.handler}`. Use the request model / validation rules in the code below; choose realistic, "
                      "small values. Respond with JSON only.\n\n" + wrap_untrusted(src[:6000], 6000))
            raw = llm.generate(prompt, max_tokens=300, json_mode=True) or ""
            try:
                data = json.loads(raw[raw.find("{"):raw.rfind("}") + 1])
            except (ValueError, json.JSONDecodeError):
                return r.handler, None
            return f"{r.method.lower()}_{_ident(r.path)}", data if isinstance(data, dict) and len(raw) < 2000 else None

        with ThreadPoolExecutor(max_workers=3, thread_name_prefix="llm-payload") as pool:
            drafted = dict(pool.map(draft, writes))
        return {k: v for k, v in drafted.items() if v}
