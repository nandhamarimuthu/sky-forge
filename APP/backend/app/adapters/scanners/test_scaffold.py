"""Per-language unit and functional test scaffolds.

Only Python suites can be *executed and validated* inside the sandbox, so for every other language SkyForge
produces a scaffold instead of an assertion it cannot prove: a compiling, idiomatic test file where each case is
explicitly skipped/pending until a human fills in the expectation. That keeps CI green on merge while still
giving the team the structure, the naming, the edge cases worth covering and the exact command to run.
"""

from __future__ import annotations

import re
from pathlib import Path

from app.adapters.scanners.languages import LANGUAGES, LanguageSpec, Symbol

# What is worth covering for a callable, derived from its arity — the same advice a reviewer would give.
EDGE_CASES = ("happy path", "empty/zero input", "boundary value", "invalid input is rejected")


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", name) if part) or "Subject"


def _snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", re.sub(r"[^0-9A-Za-z]+", "_", name)).lower().strip("_") or "subject"


def _args(sym: Symbol) -> str:
    return ", ".join(sym.params) if sym.params else ""


def _cases_for(sym: Symbol) -> tuple[str, ...]:
    if not sym.params:
        return EDGE_CASES[:2]
    if sym.complexity >= 8:
        return EDGE_CASES
    return EDGE_CASES[:3]


def _go_package(source: str) -> str:
    m = re.search(r"^package\s+(\w+)", source, re.M)
    return m.group(1) if m else "main"


# --------------------------------------------------------------------------------- unit scaffolds


def _go_unit(symbols: list[Symbol], source: str) -> str:
    out = [f"package {_go_package(source)}", "", "import \"testing\"", ""]
    for sym in symbols:
        cases = "\n".join(f'\t\t{{name: "{c}"}},' for c in _cases_for(sym))
        out += [
            f"// Test{_pascal(sym.name)} is a table-driven scaffold generated by SkyForge AI for "
            f"{sym.file}:{sym.line}.",
            f"// Fill in args/want for each case and delete the t.Skip. Signature: {sym.name}({_args(sym)})",
            f"func Test{_pascal(sym.name)}(t *testing.T) {{",
            "\tt.Parallel()",
            "\tcases := []struct {",
            "\t\tname string",
            "\t\twant any",
            "\t}{",
            cases,
            "\t}",
            "\tfor _, tc := range cases {",
            "\t\ttc := tc",
            "\t\tt.Run(tc.name, func(t *testing.T) {",
            "\t\t\tt.Parallel()",
            f'\t\t\tt.Skip("SkyForge scaffold: supply inputs for {sym.name} and assert the expected result")',
            "\t\t})",
            "\t}",
            "}",
            "",
        ]
    return "\n".join(out)


def _junit_unit(symbols: list[Symbol], rel: str, kotlin: bool = False) -> str:
    cls = _pascal(Path(rel).stem)
    suffix = "" if kotlin else ""
    out = [
        f"// Unit test scaffold generated by SkyForge AI for {rel}.",
        "// Each case is @Disabled until an expectation is supplied — enable them as you implement the assertions.",
        "",
        "import org.junit.jupiter.api.Disabled;" if not kotlin else "import org.junit.jupiter.api.Disabled",
        "import org.junit.jupiter.api.DisplayName;" if not kotlin else "import org.junit.jupiter.api.DisplayName",
        "import org.junit.jupiter.api.Test;" if not kotlin else "import org.junit.jupiter.api.Test",
        "",
        f"class {cls}Test {{" if not kotlin else f"class {cls}Test {{",
    ]
    for sym in symbols:
        for case in _cases_for(sym):
            method = f"{_snake(sym.name)}_{_snake(case)}"
            if kotlin:
                out += ["", "    @Test", "    @Disabled(\"SkyForge scaffold: supply the expectation\")",
                        f'    @DisplayName("{sym.name}: {case}")',
                        f"    fun `{sym.name} {case}`() {{",
                        f"        // Arrange / Act / Assert for {sym.qualname}({_args(sym)}) — {rel}:{sym.line}",
                        "        TODO(\"assert the expected result\")", "    }"]
            else:
                out += ["", "    @Test", "    @Disabled(\"SkyForge scaffold: supply the expectation\")",
                        f'    @DisplayName("{sym.name}: {case}")',
                        f"    void {method}() {{",
                        f"        // Arrange / Act / Assert for {sym.qualname}({_args(sym)}) — {rel}:{sym.line}",
                        "        // assertEquals(expected, actual);", "    }"]
    out += ["}", ""]
    return "\n".join(x for x in out if x is not None) + suffix


def _xunit_unit(symbols: list[Symbol], rel: str) -> str:
    cls = _pascal(Path(rel).stem)
    out = [f"// Unit test scaffold generated by SkyForge AI for {rel}.", "", "using Xunit;", "",
           f"public class {cls}Tests", "{"]
    for sym in symbols:
        for case in _cases_for(sym):
            out += ["", '    [Fact(Skip = "SkyForge scaffold: supply the expectation")]',
                    f"    public void {_pascal(sym.name)}_{_pascal(case)}()", "    {",
                    f"        // {sym.qualname}({_args(sym)}) — {rel}:{sym.line}",
                    "        // Assert.Equal(expected, actual);", "    }"]
    out += ["}", ""]
    return "\n".join(out)


def _rspec_unit(symbols: list[Symbol], rel: str) -> str:
    out = [f"# Unit spec scaffold generated by SkyForge AI for {rel}.", "# Each example is `pending` until you "
           "supply the expectation.", "", f"RSpec.describe '{Path(rel).stem}' do"]
    for sym in symbols:
        out += ["", f"  describe '#{sym.name}' do"]
        for case in _cases_for(sym):
            out += [f"    it '{case}' do",
                    f"      pending 'SkyForge scaffold: call {sym.name}({_args(sym)}) and assert the result'",
                    "      raise 'not implemented'", "    end"]
        out += ["  end"]
    out += ["end", ""]
    return "\n".join(out)


def _phpunit_unit(symbols: list[Symbol], rel: str) -> str:
    cls = _pascal(Path(rel).stem)
    out = ["<?php", "", f"// Unit test scaffold generated by SkyForge AI for {rel}.", "",
           "use PHPUnit\\Framework\\TestCase;", "", f"final class {cls}Test extends TestCase", "{"]
    for sym in symbols:
        for case in _cases_for(sym):
            out += ["", f"    public function test{_pascal(sym.name)}{_pascal(case)}(): void", "    {",
                    f"        $this->markTestIncomplete('SkyForge scaffold: {sym.name}({_args(sym)}) — "
                    f"{rel}:{sym.line}');", "    }"]
    out += ["}", ""]
    return "\n".join(out)


def _rust_unit(symbols: list[Symbol], rel: str) -> str:
    out = [f"// Unit test scaffold generated by SkyForge AI for {rel}.", "",
           "#[cfg(test)]", "mod skyforge_tests {", "    #[allow(unused_imports)]", "    use super::*;"]
    for sym in symbols:
        for case in _cases_for(sym):
            out += ["", "    #[test]",
                    '    #[ignore = "SkyForge scaffold: supply inputs and expectation"]',
                    f"    fn {_snake(sym.name)}_{_snake(case)}() {{",
                    f"        // {sym.name}({_args(sym)}) — {rel}:{sym.line}",
                    "        // assert_eq!(expected, actual);", "    }"]
    out += ["}", ""]
    return "\n".join(out)


def _js_unit(symbols: list[Symbol], rel: str, typescript: bool) -> str:
    runner = "vitest" if typescript else "jest"
    imports = ('import { describe, it, expect } from "vitest";\n' if typescript else "")
    rel_import = "../" + Path(rel).stem
    names = ", ".join(sorted({s.name for s in symbols})[:12])
    out = [f"// Unit test scaffold generated by SkyForge AI for {rel} ({runner}).",
           "// Each case is skipped until you supply the expectation.", "", imports.rstrip(),
           f'// import {{ {names} }} from "{rel_import}";', ""]
    for sym in symbols:
        out += [f'describe("{sym.name}", () => {{']
        for case in _cases_for(sym):
            out += [f'  it.skip("{case}", () => {{',
                    f"    // {sym.name}({_args(sym)}) — {rel}:{sym.line}",
                    "    // expect(actual).toEqual(expected);", "  });"]
        out += ["});", ""]
    return "\n".join(out)


def _scala_unit(symbols: list[Symbol], rel: str) -> str:
    cls = _pascal(Path(rel).stem)
    out = [f"// Unit spec scaffold generated by SkyForge AI for {rel}.", "",
           "import org.scalatest.flatspec.AnyFlatSpec", "import org.scalatest.matchers.should.Matchers", "",
           f"class {cls}Spec extends AnyFlatSpec with Matchers {{"]
    for sym in symbols:
        for case in _cases_for(sym):
            out += ["", f'  it should "{sym.name}: {case}" in pending  // {rel}:{sym.line}']
    out += ["}", ""]
    return "\n".join(out)


def _swift_unit(symbols: list[Symbol], rel: str) -> str:
    cls = _pascal(Path(rel).stem)
    out = [f"// Unit test scaffold generated by SkyForge AI for {rel}.", "", "import XCTest", "",
           f"final class {cls}Tests: XCTestCase {{"]
    for sym in symbols:
        for case in _cases_for(sym):
            out += ["", f"    func test{_pascal(sym.name)}{_pascal(case)}() throws {{",
                    f'        try XCTSkipIf(true, "SkyForge scaffold: {sym.name}({_args(sym)}) — {rel}:{sym.line}")',
                    "    }"]
    out += ["}", ""]
    return "\n".join(out)


def render_unit_scaffold(language: str, rel: str, symbols: list[Symbol], source: str = "") -> str | None:
    """A compiling, idiomatic (and explicitly pending) unit test file for `rel`. None if unsupported."""
    symbols = [s for s in symbols if s.exported][:8] or symbols[:8]
    if not symbols:
        return None
    if language == "go":
        return _go_unit(symbols, source)
    if language == "java":
        return _junit_unit(symbols, rel)
    if language == "kotlin":
        return _junit_unit(symbols, rel, kotlin=True)
    if language == "csharp":
        return _xunit_unit(symbols, rel)
    if language == "ruby":
        return _rspec_unit(symbols, rel)
    if language == "php":
        return _phpunit_unit(symbols, rel)
    if language == "rust":
        return _rust_unit(symbols, rel)
    if language in ("javascript", "typescript"):
        return _js_unit(symbols, rel, typescript=language == "typescript")
    if language == "scala":
        return _scala_unit(symbols, rel)
    if language == "swift":
        return _swift_unit(symbols, rel)
    return None


# --------------------------------------------------------------------------------- functional scaffolds

_FUNCTIONAL_HEADERS: dict[str, tuple[str, str]] = {
    "go": ("tests/skyforge_functional/journeys_test.go", "go test ./tests/... -run Journey"),
    "java": ("src/test/java/SkyForgeJourneyTest.java", "mvn -q test -Dtest=SkyForgeJourneyTest"),
    "kotlin": ("src/test/kotlin/SkyForgeJourneyTest.kt", "gradle test --tests SkyForgeJourneyTest"),
    "csharp": ("tests/SkyForgeJourneyTests.cs", "dotnet test --filter SkyForgeJourney"),
    "ruby": ("spec/requests/skyforge_journeys_spec.rb", "bundle exec rspec spec/requests"),
    "php": ("tests/Feature/SkyForgeJourneyTest.php", "vendor/bin/phpunit --testsuite Feature"),
    "rust": ("tests/skyforge_journeys.rs", "cargo test --test skyforge_journeys"),
}


def render_functional_scaffold(language: str, routes: list[dict]) -> tuple[str, str, str] | None:
    """(path, content, runner) for an HTTP journey suite in `language`, or None when unsupported."""
    header = _FUNCTIONAL_HEADERS.get(language)
    if not header or not routes:
        return None
    path, runner = header
    routes = routes[:40]
    if language == "go":
        body = ["// HTTP journey scaffold generated by SkyForge AI.", "//",
                "// Wire `handler` to your real router (e.g. the mux returned by NewRouter) and remove t.Skip.",
                "package skyforge_functional", "", "import (", '\t"net/http"', '\t"net/http/httptest"',
                '\t"testing"', ")", "",
                "func TestHTTPJourneys(t *testing.T) {", "\tcases := []struct {",
                "\t\tmethod, path string", "\t\trequiresAuth bool", "\t}{"]
        for r in routes:
            body.append(f'\t\t{{"{r["method"]}", "{r["path"]}", {str(r["requires_auth"]).lower()}}},')
        body += ["\t}", "\tfor _, tc := range cases {",
                 "\t\tt.Run(tc.method+\" \"+tc.path, func(t *testing.T) {",
                 '\t\t\tt.Skip("SkyForge scaffold: pass your router to httptest and assert the status")',
                 "\t\t\treq := httptest.NewRequest(tc.method, tc.path, nil)",
                 "\t\t\trec := httptest.NewRecorder()",
                 "\t\t\tvar handler http.Handler // = NewRouter()",
                 "\t\t\thandler.ServeHTTP(rec, req)",
                 "\t\t\tif rec.Code >= 500 {",
                 '\t\t\t\tt.Fatalf("%s %s returned %d", tc.method, tc.path, rec.Code)', "\t\t\t}",
                 "\t\t\tif tc.requiresAuth && rec.Code != http.StatusUnauthorized && "
                 "rec.Code != http.StatusForbidden {",
                 '\t\t\t\tt.Fatalf("%s %s is reachable without authentication (%d)", tc.method, tc.path, rec.Code)',
                 "\t\t\t}", "\t\t})", "\t}", "}", ""]
        return path, "\n".join(body), runner
    if language in ("java", "kotlin"):
        kt = language == "kotlin"
        semi = "" if kt else ";"
        lines = [f"// HTTP journey scaffold generated by SkyForge AI ({len(routes)} routes).",
                 "// Uses Spring MockMvc — swap in RestAssured/WebTestClient if that is your stack.", "",
                 f"import org.junit.jupiter.api.Disabled{semi}", f"import org.junit.jupiter.api.Test{semi}", "",
                 "class SkyForgeJourneyTest {"]
        for r in routes:
            name = re.sub(r"[^0-9A-Za-z]+", "_", f"{r['method']}_{r['path']}").strip("_").lower()
            lines += ["", "    @Test", '    @Disabled("SkyForge scaffold: wire MockMvc and assert the status")']
            if kt:
                lines += [f"    fun `{r['method']} {r['path']} does not error`() {{",
                          f"        // mockMvc.perform({r['method'].lower()}(\"{r['path']}\"))"
                          ".andExpect(status().is4xxClientError)", "    }"]
            else:
                lines += [f"    void {name}_does_not_error() {{",
                          f"        // mockMvc.perform({r['method'].lower()}(\"{r['path']}\"))"
                          ".andExpect(status().isOk());", "    }"]
        lines += ["}", ""]
        return path, "\n".join(lines), runner
    if language == "csharp":
        lines = [f"// HTTP journey scaffold generated by SkyForge AI ({len(routes)} routes).",
                 "// Uses WebApplicationFactory<Program> for in-process requests — no deployed environment.", "",
                 "using System.Net;", "using System.Threading.Tasks;", "using Xunit;", "",
                 "public class SkyForgeJourneyTests", "{"]
        for r in routes:
            name = _pascal(re.sub(r"[^0-9A-Za-z]+", " ", f"{r['method']} {r['path']}"))
            lines += ["", '    [Fact(Skip = "SkyForge scaffold: create the test client and assert the status")]',
                      f"    public async Task {name}_DoesNotError()", "    {",
                      f'        // var response = await _client.{r["method"].capitalize()}Async("{r["path"]}");',
                      "        // Assert.True((int)response.StatusCode < 500);", "        await Task.CompletedTask;",
                      "    }"]
        lines += ["}", ""]
        return path, "\n".join(lines), runner
    if language == "ruby":
        lines = [f"# HTTP journey scaffold generated by SkyForge AI ({len(routes)} routes).", "",
                 "require 'rails_helper'", "", "RSpec.describe 'HTTP journeys', type: :request do"]
        for r in routes:
            lines += [f"  it '{r['method']} {r['path']} does not return a server error' do",
                      f"    pending 'SkyForge scaffold: supply params/auth for {r['path']}'",
                      f"    {r['method'].lower()} '{r['path']}'",
                      "    expect(response.status).to be < 500", "  end"]
            if r["requires_auth"]:
                lines += [f"  it '{r['method']} {r['path']} requires authentication' do",
                          "    pending 'SkyForge scaffold: assert the unauthenticated response'",
                          f"    {r['method'].lower()} '{r['path']}'",
                          "    expect(response.status).to be_in([401, 403, 302])", "  end"]
        lines += ["end", ""]
        return path, "\n".join(lines), runner
    if language == "php":
        lines = ["<?php", "", f"// HTTP journey scaffold generated by SkyForge AI ({len(routes)} routes).", "",
                 "use Tests\\TestCase;", "", "final class SkyForgeJourneyTest extends TestCase", "{"]
        for r in routes:
            name = _pascal(re.sub(r"[^0-9A-Za-z]+", " ", f"{r['method']} {r['path']}"))
            lines += ["", f"    public function test{name}DoesNotError(): void", "    {",
                      f"        $this->markTestIncomplete('SkyForge scaffold: assert {r['method']} {r['path']}');",
                      f"        // $this->{r['method'].lower()}('{r['path']}')->assertSuccessful();", "    }"]
        lines += ["}", ""]
        return path, "\n".join(lines), runner
    if language == "rust":
        lines = [f"// HTTP journey scaffold generated by SkyForge AI ({len(routes)} routes).", ""]
        for r in routes:
            name = _snake(f"{r['method']}_{r['path']}")
            lines += ["#[test]", '#[ignore = "SkyForge scaffold: build the app and assert the status"]',
                      f"fn {name}_does_not_error() {{",
                      f"    // call {r['method']} {r['path']} through actix/axum test utilities", "}", ""]
        return path, "\n".join(lines), runner
    return None


def runner_for(language: str) -> str:
    spec: LanguageSpec | None = LANGUAGES.get(language)
    return spec.runner if spec else ""
